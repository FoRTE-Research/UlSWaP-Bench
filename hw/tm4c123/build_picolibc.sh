#!/bin/bash
set -e

SCRIPT_DIR=$(dirname "$(readlink -f "$0")")

# Referenced by paths in config.env, so export it before sourcing.
export BENCHMARKS_ROOT=$(readlink -f "$SCRIPT_DIR/../..")

# Same file the CMake build and the test harness read, so the toolchain and
# install locations here can never drift from theirs.
set -a
. "$SCRIPT_DIR/config.env"
set +a

BUILD_DIR=$PICOLIBC_BUILD_DIR
INSTALL_DIR=$PICOLIBC_INSTALL_DIR

mkdir -p "$BUILD_DIR" "$INSTALL_DIR"

# Generated and written to the build directory rather than checked in
CROSS_FILE=$BUILD_DIR/picolibc_meson_cross_config.txt

cat > "$CROSS_FILE" <<EOF
# Generated by build_picolibc.sh from hw/tm4c123/config.env -- do not edit.
[binaries]
c       = '$CC'
ar      = '$AR'
nm      = '$NM'
strip   = '$STRIP'
objdump = '$OBJDUMP'
ranlib  = '$RANLIB'

[host_machine]
system     = 'none'
cpu_family = 'arm'
cpu        = '$CPU'
endian     = 'little'

[properties]
skip_sanity_check = true
EOF

cd "$BUILD_DIR"

meson setup \
    --reconfigure \
    --cross-file "$CROSS_FILE" \
    -Dincludedir="include" \
    -Dlibdir="lib" \
    -Dspecsdir="specs" \
    -Dtests=false \
    -Dsysroot-install=false \
    -Dsystem-libc=false \
    -Dfreestanding=true \
    -Dpicocrt=false \
    -Dsemihost=false \
    -Dprefix="$INSTALL_DIR" \
    "$PICOLIBC_ROOT"

ninja -j"$(nproc)"
ninja install
